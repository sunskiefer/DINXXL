#!/usr/bin/env python3
"""Writes everything that follows from tools/spec.py and tools/panel_labels.py:

    python3 tools/gen_params.py

  params.json       the VST parameter list for mpc-vst-plugins' gen_vst.py (index = order; append-only once shipped)
  src/param_ids.h   P_<KEY> indices, tables for the engine
  layout.conf       the skin layout (3 tabs: KEYS + SCREEN, DRUMS, SYNTH)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
import spec  # noqa: E402
import panel_labels as PL  # noqa: E402

Y0 = 86            # Force Shadow y of the plugin page's top
INK = "e9e9e6"
GREEN = "1ab463"
GREY = "9a9a9a"
FONT = "art/fonts/ChakraPetch-Medium.ttf"
OFF_ON = ["Off", "On"]
WAVES = ["", "Sine", "Half Sine", "Abs Sine", "Pulse Sine", "Sine Even", "Abs Even", "Square", "Derived Square"]
ALGOS = ["", "Algo 1", "Algo 2", "Algo 3", "Algo 4", "Algo 5"]

# what the faders start at (a basic kit on a blank machine; the factory SD kits are not part of the firmware repo)
DEFAULTS = {"vol": 120, "wav": 0, "fbk": 0, "mult": 20, "tune": 64, "fall": 40, "att": 0, "dec": 70,
            "trem": 0, "vibra": 0, "algo": 0}


def fader_default(key):
    return DEFAULTS.get(key.split("_", 1)[1], 0)


def trig(key, name):
    return {"key": key, "name": name, "min": 0.0, "max": 1.0, "default": 0.0, "momentary": True, "type": "trigger"}


def build():
    P = []
    # 1) the 56 faders (firmware movedFader() numbers in spec.py)
    for key, label, fw, cx, row in spec.FADERS:
        P.append({"key": key, "name": label, "min": 0.0, "max": 127.0, "default": float(fader_default(key)),
                  "display": "int"})
    # 2) the keys: voice keys, step keys (momentary), modifier keys (latching), RUN
    for key, label, fw in spec.VOICE_KEYS:
        P.append(trig("kv_" + key[2:], "Key " + label))
    for s, nm in enumerate(spec.STEP_NAMES):
        P.append(trig("ks_%d" % (s + 1), "Key %d %s" % (s + 1, nm.title())))
    for key, label, fw, cx, cy, latch in spec.MODE_KEYS:   # a tap, like every key; HOLD keeps one down
        P.append(trig("km_" + key[2:], "Key " + label))
    P.append(trig("k_run", "Key Run"))
    # 3) the lamps (the machine sets them; the skin shows them)
    for key, label, fw in spec.VOICE_KEYS:
        P.append({"key": "lv_" + key[2:], "name": "Lamp " + label, "options": OFF_ON, "default": 0})
    for s, nm in enumerate(spec.STEP_NAMES):
        P.append({"key": "ls_%d" % (s + 1), "name": "Lamp Step %d" % (s + 1), "options": OFF_ON, "default": 0})
    for key, led, cx, cy in spec.MODE_LAMPS:
        P.append({"key": key.replace("l_", "lm_"), "name": "Lamp " + key[2:].title(), "options": OFF_ON, "default": 0})
    # 4) the screen
    for i in range(1, 6):
        P.append({"key": "scr_t%d" % i, "name": "Screen Text %d" % i, "min": 0.0, "max": 0.0, "default": 0.0,
                  "display": "string"})
    P.append({"key": "scr_wave", "name": "Screen Wave", "options": WAVES, "default": 0})
    P.append({"key": "scr_algo", "name": "Screen Algo", "options": ALGOS, "default": 0})
    # 5) HOLD (the plugin's own key, see spec.HOLD_KEY): latches; while on, voice and step key taps toggle a hold
    P.append({"key": "k_hold", "name": "Key Hold", "options": OFF_ON, "default": 0})
    # 6) how the Force's pads reach the machine: one voice per pad (default) or the machine's own chromatic channels
    P.append({"key": "pad_mode", "name": "Pads", "options": ["PADS = VOICES", "CHROMATIC"], "default": 0})
    sections = [
        {"label": "DRUMS", "keys": [f[0] for f in spec.DRUM_FADERS]},
        {"label": "SYNTH", "keys": [f[0] for f in spec.SYNTH_FADERS]},
        {"label": "KEYS", "keys": ["kv_" + k[0][2:] for k in spec.VOICE_KEYS] + ["ks_%d" % (i + 1) for i in range(16)] +
                                  ["km_" + k[0][2:] for k in spec.MODE_KEYS] + ["k_run", "k_hold", "pad_mode"]},
    ]
    return {"name": "DINXXL", "params": P, "sections": sections}


def write_ids(params):
    L = ["// GENERATED by tools/gen_params.py from tools/spec.py. Do not edit.", "#pragma once", "enum ParamId {"]
    for i, p in enumerate(params["params"]):
        L.append("  P_%s = %d," % (p["key"].upper(), i))
    L.append("  P_COUNT = %d" % len(params["params"]))
    L.append("};")
    L.append("")
    nF, nV, nS, nM = len(spec.FADERS), len(spec.VOICE_KEYS), 16, len(spec.MODE_KEYS)
    a = 0
    L.append("// groups (parameter order is fixed: faders, keys, lamps, screen)")
    for nm, n in (("FADER", nF), ("VKEY", nV), ("SKEY", nS), ("MKEY", nM), ("RUN", 1), ("VLAMP", nV), ("SLAMP", nS),
                  ("MLAMP", len(spec.MODE_LAMPS)), ("SCR", 5), ("WAVE", 1), ("ALGO", 1)):
        L.append("static const int IDX_%s = %d, N_%s = %d;" % (nm, a, nm, n))
        a += n
    L.append("static const char* const PARAM_KEY[P_COUNT] = {%s};" % ", ".join('"%s"' % p["key"] for p in params["params"]))
    L.append("struct ParamInfo { const char* key; const char* name; int kind; int fw; };   // kind: see engine.cc")
    L.append("// faders: firmware fader number")
    L.append("static const int FADER_FW[56] = {%s};" % ", ".join(str(f[2]) for f in spec.FADERS))
    L.append("static const char* const FADER_NAME[56] = {%s};" % ", ".join('"%s"' % f[1] for f in spec.FADERS))
    L.append("static const char* const FADER_KEY[56] = {%s};" % ", ".join('"%s"' % f[0] for f in spec.FADERS))
    L.append("static const int FADER_DEFAULT[56] = {%s};" % ", ".join(str(fader_default(f[0])) for f in spec.FADERS))
    L.append("static const int VOICE_KEY_FW[10] = {%s};" % ", ".join(str(v[2]) for v in spec.VOICE_KEYS))
    L.append("static const int STEP_KEY_FW[16] = {%s};" % ", ".join(str(b) for b in spec.STEP_BUTTON))
    L.append("static const int MODE_KEY_FW[5] = {%s};" % ", ".join(str(m[2]) for m in spec.MODE_KEYS))
    L.append("static const int MODE_LAMP_LED[6] = {%s};" % ", ".join(str(m[1]) for m in spec.MODE_LAMPS))
    open(os.path.join(ROOT, "src", "param_ids.h"), "w").write("\n".join(L) + "\n")


# ------------------------------------------------------------------------------------------------ layout
def Y(y):
    return int(round(y + Y0))


PX_SCALE = 0.91     # the renderer's text comes out about 10% larger than the same size in the panel sketches


def natural_width(label, px):
    from PIL import ImageFont
    return ImageFont.truetype(os.path.join(ROOT, FONT), 100).getlength(label) * px / 100.0


def text(cx, cy_base, label, px=28, color=INK, align="center", weight=500, fit=None):
    """Live static text: cy is where the SVG baseline was; the widget wants the visual centre.
    fit: the width the printed caption was squeezed into (the text shrinks to fit it)."""
    if fit and natural_width(label, px * PX_SCALE) > fit:
        px = px * fit / natural_width(label, px * PX_SCALE)
    cy = cy_base - 0.36 * px
    return 'text cx=%d cy=%d label="%s" size=%.2f color=%s align=%s weight=%d fontfile=%s' % (
        round(cx), Y(cy), label, px * PX_SCALE / 10.0, color, align, weight, FONT)


def build_layout(params):
    L = []
    L.append("# DINXXL page layout. GENERATED by tools/gen_params.py from tools/spec.py -- edit those, not this.")
    L.append("scale_names=1")
    L.append("label_scale=1.25")
    for k, v in [("bg", "141414"), ("panel", "141414"), ("line", "bdbdbd"), ("ink", "f0f0f0"), ("ink_dim", "c4c4c4"),
                 ("ink_faint", "777777"), ("accent", GREEN), ("accent_hi", "ffffff"), ("knob_face", "141414"),
                 ("knob_ring", "3a3a3a"), ("knob_dot", "f0f0f0"), ("bar", "141414"), ("seg_active", GREEN),
                 ("seg_inactive", "111111"), ("seg_active_tx", "111111"), ("btn_text", "f0f0f0"), ("tab_on", GREEN),
                 ("tab_on_tx", "111111"), ("lcd", "0d0d0d"), ("box", "111111")]:
        L.append("theme_%s=%s" % (k, v))
    q = qlink_sets()
    L.append("qlinks_track = " + ",".join(q[0][1]))
    L.append("")
    # ---------------------------------------------------------------- KEYS tab
    L.append("[tab KEYS]")
    L.append("art file=art/bg_keys.png x=0 y=%d w=1280 h=628" % Y0)
    # live captions
    for lab, x in zip(PL.VOX, PL.KEYX[:10]):
        L.append(text(x, PL.VOX_Y, lab, 26, fit=64 if lab.startswith("synth") else None))
    for lab, x, y in PL.MODE_LABELS:
        L.append(text(x, y, lab, 26, fit=74 if lab in ("kit/patt", "function") else None))
    for txt, x in PL.GROUP_TEXT:
        L.append(text(x, PL.LY + 9, txt, 26))
    # the lamps (sprites; an off lamp is part of the background)
    for key, label, fw in spec.VOICE_KEYS:
        i = [k[0] for k in spec.VOICE_KEYS].index(key)
        L.append("art file=art/lamp_on.png x=%d y=%d w=35 h=35 when=lv_%s:1" % (spec.VOICE_X[i] - 17, Y(spec.VOICE_LAMP_Y - 17), key[2:]))
    for s in range(16):
        L.append("art file=art/lamp_on.png x=%d y=%d w=35 h=35 when=ls_%d:1" % (spec.STEP_X[s] - 17, Y(spec.STEP_LAMP_Y - 17), s + 1))
    for key, led, cx, cy in spec.MODE_LAMPS:
        if key == "l_rec":
            L.append("art file=art/lamp_rec_on.png x=%d y=%d w=29 h=29 when=%s:1" % (284 - 14, Y(192 - 14), key.replace("l_", "lm_")))
        else:
            L.append("art file=art/lamp_on.png x=%d y=%d w=35 h=35 when=%s:1" % (cx - 17, Y(cy - 17), key.replace("l_", "lm_")))
    # the keys
    for i, (key, label, fw) in enumerate(spec.VOICE_KEYS):
        L.append('button cx=%d cy=%d label="" key=kv_%s img=art/clear.png img_on=art/press.png w=%d h=%d' % (
            spec.VOICE_X[i], Y(spec.VOICE_Y), key[2:], spec.KEY_W, spec.KEY_H))
    for s in range(16):
        L.append('button cx=%d cy=%d label="" key=ks_%d img=art/clear.png img_on=art/press.png w=%d h=%d' % (
            spec.STEP_X[s], Y(spec.STEP_Y), s + 1, spec.KEY_W, spec.KEY_H))
    for key, label, fw, cx, cy, latch in spec.MODE_KEYS:
        L.append('button cx=%d cy=%d label="" key=km_%s img=art/clear.png img_on=art/press.png w=%d h=%d' % (
            cx, Y(cy), key[2:], spec.KEY_W, spec.KEY_H))
    L.append('button cx=%d cy=%d label="" key=k_run img=art/clear.png img_on=art/press.png w=%d h=%d' % (
        spec.RUN_KEY[2], Y(spec.RUN_KEY[3]), spec.KEY_W, spec.KEY_H))
    hk, hl, hcx, hcy, hw_, hh = spec.HOLD_KEY
    lx, ly, hh = [int(v) for v in open("art/hold_lamp.txt").read().split()]
    L.append("art file=art/lamp_on.png x=%d y=%d w=35 h=35 when=%s:1" % (lx - 17, Y(ly - 17), hk))
    L.append('toggle cx=%d cy=%d label="" key=%s img=art/clear.png img_on=art/clear.png w=%d h=%d ns=0' % (hcx, Y(hcy), hk, hw_, hh))
    L.append(text(hcx, 50, hl, 26, align="center"))
    L.append('toggle cx=215 cy=%d label="" key=pad_mode img=art/pads_voices.png img_on=art/pads_chrom.png w=300 h=36 ns=0' % Y(15))
    # the screen
    L.append("picture x=%d y=%d w=240 h=100 key=scr_wave files=\"%s\"" % (452 + spec.SCREEN_DX, Y(172), ",".join("art/wave_%d.png" % i for i in range(9))))
    L.append("picture x=%d y=%d w=240 h=100 key=scr_algo files=\"%s\"" % (452 + spec.SCREEN_DX, Y(172), ",".join("art/algo_%d.png" % i for i in range(6))))
    L.append('readout cx=%d cy=%d w=300 h=64 label="" key=scr_t1 tsize=56 tcolor=%s tweight=600 talign=left' % (592 + spec.SCREEN_DX, Y(96), GREEN))
    L.append('readout cx=%d cy=%d w=300 h=40 label="" key=scr_t2 tsize=30 tcolor=%s tweight=500 talign=left' % (592 + spec.SCREEN_DX, Y(146), GREY))
    L.append('readout cx=%d cy=%d w=380 h=40 label="" key=scr_t3 tsize=30 tcolor=%s tweight=500 talign=left' % (890 + spec.SCREEN_DX, Y(104), GREY))
    L.append('readout cx=%d cy=%d w=380 h=80 label="" key=scr_t4 tsize=64 tcolor=%s tweight=600 talign=left' % (890 + spec.SCREEN_DX, Y(172), GREEN))
    L.append('readout cx=%d cy=%d w=380 h=40 label="" key=scr_t5 tsize=26 tcolor=%s tweight=500 talign=left' % (890 + spec.SCREEN_DX, Y(250), GREY))
    L.append("")
    # ---------------------------------------------------------------- faders
    def fader_tab(name, bg, faders, base, labels_t, labels_b, pairs_t, pairs_b, rot_note=None):
        L.append("[tab %s]" % name)
        L.append("art file=%s x=0 y=%d w=1280 h=628" % (bg, Y0))
        # the captions are the panel's own printed ones (nothing is drawn over them)
        for key, label, fw, cx, row in faders:
            y0, y1 = spec.ROW_TOP[row]
            L.append('slider_v cx=%d cy=%d w=26 h=%d label="%s" key=%s img=art/cap.png base=art/clear.png ns=0 vs=0 bw=60' % (
                cx, Y((y0 + y1) / 2), y1 - y0 - 10, label, key))
        for name2, keys2 in q:
            if name2.startswith(name):
                L.append('qlinks "%s" = %s' % (name2, ",".join(keys2)))
        L.append("")
    # drum labels: the label lists of the printed panel (op pages carry the per-slot names)
    fader_tab("DRUMS", "art/bg_drum.png", spec.DRUM_FADERS, PL.DRUM_BASE, PL.DRUM_LABELS_T, PL.DRUM_LABELS_B,
              PL.DRUM_PAIRS_T, PL.DRUM_PAIRS_B)
    fader_tab("SYNTH", "art/bg_synth.png", spec.SYNTH_FADERS, PL.SYNTH_BASE, PL.OP1 + PL.OP2, PL.OP3 + PL.OP4, [], [])
    return "\n".join(L) + "\n"


def qlink_sets():
    d = [f[0] for f in spec.DRUM_FADERS]
    s = [f[0] for f in spec.SYNTH_FADERS]
    return [("DRUMS 1", d[:16]), ("DRUMS 2", d[16:] + [None] * 4), ("SYNTH 1", s[:16]), ("SYNTH 2", s[16:] + [None] * 4)]


def main():
    params = build()
    # qlink sets: drop the padding (a set may be shorter than 16)
    global qlink_sets
    base = qlink_sets
    qlink_sets = lambda: [(n, [k for k in ks if k]) for n, ks in base()]  # noqa: E731
    json.dump(params, open(os.path.join(ROOT, "params.json"), "w"), indent=1)
    write_ids(params)
    open(os.path.join(ROOT, "layout.conf"), "w").write(build_layout(params))
    print("params:", len(params["params"]))


if __name__ == "__main__":
    main()
