// Virtual BlastBeats hardware. The unchanged firmware runs against this: a clock, the mux'd
// faders and keys, the MAX7219 lamp matrix, the three TPA6130A2 amps, MIDI UART, the SD card
// and the YMF262 sound chip (ymfm). Everything the firmware reads or writes goes through here.
#pragma once
#include <stdint.h>
#include <vector>
#include <string>

namespace hw {
enum { N_FADERS = 56, N_KEYS = 32 };

struct Amp { uint8_t reg1 = 0, reg2 = 0; };

void reset(uint32_t seed);            // power-on: clears the machine (SD card kept)
void advance(uint32_t us);            // run virtual time, firing timers and the sound chip
uint64_t now_us();

// panel -> machine
void set_fader(int idx, int v127);    // idx 0..55, v 0..127
int  get_fader(int idx);
void set_key(int idx, bool down);     // idx 0..31 (mux keys)
void set_run_key(bool down);          // RUN is on its own pin

// machine -> panel
bool lamp(int led_number);            // firmware LED number (setLed numbering)
uint8_t lamp_row(int row);
const Amp& amp(int which);            // 0 = out 1-4, 1 = phones, 2 = mix
int  mix_gain64();                    // 0..63 from the mix amp register

// audio: pull 44.1 kHz stereo (float -1..1) generated by the chip
void audio_pull(float* lr, int frames);
int  audio_fill();
void audio_trim(int keep);            // drop the newest samples beyond `keep` native samples                    // native samples buffered

// MIDI UART (DIN) bytes
void midi_in(uint8_t b);
bool midi_out(uint8_t* b);

// SD card (saved with the host project)
std::string sd_save();
void sd_load(const std::string& blob);
// the factory card: a zlib-packed card image (tools/pack_card.py). Loading it also remembers it, so the project only has
// to keep what differs from it (sd_save_diff / sd_apply_diff).
bool sd_load_factory_file(const std::string& path);
bool sd_has_factory();
void sd_reset_to_factory();
std::string sd_save_diff();
void sd_apply_diff(const std::string& blob);
}
